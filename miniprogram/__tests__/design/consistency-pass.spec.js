const fs = require('fs');
const path = require('path');

const projectRoot = path.join(process.cwd(), 'miniprogram');
const appConfig = JSON.parse(fs.readFileSync(path.join(projectRoot, 'app.json'), 'utf8'));
const read = file => fs.readFileSync(path.join(process.cwd(), file), 'utf8');

function registeredPages() {
  const pages = [...appConfig.pages];
  for (const subPackage of appConfig.subPackages || []) {
    for (const page of subPackage.pages) pages.push(`${subPackage.root}/${page}`);
  }
  return pages;
}

describe('miniprogram version 2 consistency', () => {
  test('every registered page has a balanced WXSS file with a polish marker', () => {
    for (const page of registeredPages()) {
      const file = `miniprogram/${page}.wxss`;
      expect(fs.existsSync(path.join(process.cwd(), file))).toBe(true);
      const styles = read(file);
      const marker = page === 'pages/meeting-webview/meeting-webview'
        ? 'Version 2 consistency polish'
        : /(Version 1|Version 2) core|consistency polish|Version 3 dawn/; // 晨光之后新建的页面直接按晨光规范写，标记为 Version 3 dawn

      expect(styles).toMatch(marker);
      expect(styles).toMatch(/var\(--(?:app|theme)-/);
      expect(styles).not.toContain('rpxpx');

      let depth = 0;
      for (const char of styles) {
        if (char === '{') depth += 1;
        if (char === '}') depth -= 1;
        expect(depth).toBeGreaterThanOrEqual(0);
      }
      expect(depth).toBe(0);
    }
  });

  test('version 2 covers all remaining package page groups', () => {
    const expected = [
      'pages/courses/courses',
      'pages/checkin/checkin',
      'pages/insights/insights',
      'pages/insight-requests/insight-requests',
      'pages/podcast-player/podcast-player',
      'pages/zaichang/list/list',
      'pages/zaichang/detail/detail',
      'pages/zaichang/publish/publish',
      'pages/admin-analytics/admin-analytics',
      'pages/admin-workbench/admin-workbench',
      'pages/notifications/notifications',
      'pages/completion-reports/completion-reports',
      'pages/ranking/ranking'
    ];

    for (const page of expected) {
      expect(read(`miniprogram/${page}.wxss`)).toContain('Version 2 consistency polish');
    }
  });

  test('theme alpha variables used by runtime styles are generated by the tenant theme', () => {
    const generated = read('miniprogram/theme.wxss');
    const defined = new Set(
      [...generated.matchAll(/--theme-primary-alpha-(\d+)/g)].map(match => match[1])
    );
    const used = [];

    function collect(dir) {
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) collect(fullPath);
        if (entry.isFile() && entry.name.endsWith('.wxss')) {
          const styles = fs.readFileSync(fullPath, 'utf8');
          for (const match of styles.matchAll(/var\(--theme-primary-alpha-(\d+)/g)) {
            used.push({ file: path.relative(process.cwd(), fullPath), alpha: match[1] });
          }
        }
      }
    }

    collect(projectRoot);
    expect(used.length).toBeGreaterThan(20);
    for (const item of used) {
      if (!defined.has(item.alpha)) throw new Error(`Undefined theme alpha: ${item.file}:${item.alpha}`);
    }
  });

  test('floating actions and long landing pages respect the safe area', () => {
    expect(read('miniprogram/pages/zaichang/list/list.wxss')).toContain('calc(32rpx + env(safe-area-inset-bottom))');
    expect(read('miniprogram/pages/invite/invite.wxss')).toContain('calc(28rpx + env(safe-area-inset-bottom))');
  });
});
